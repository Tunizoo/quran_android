# ----------------------------------------------------------------------------- generation

ALLAH_RES = [re.compile("^(و|ف|ا|ء)?(ب|ت)?الله(م)?$"), re.compile("^(و|ف|ا)?لله$"),
             re.compile("^(و|ف|ا)?(ب|ل|ك)?رب(ي|ك|كم|كما|نا|ه|ها|هم|هما|هن)$")]

def ayah_has_allah_reference(ntoks):
    return any(r.match(n) for n in ntoks for r in ALLAH_RES)

def is_definite(n):
    return re.match("^(و|ف)?(ب|ك)?(ال|لل)", n) is not None

def in_set(st, s, a, pos):
    return (s, a) in st or (s, a, pos) in st

def main():
    glyphs = load_glyphs()
    v2 = sqlite3.connect(os.path.join(DB, "quran.ar.uthmani.v2.db"))
    ayahs = v2.execute("select sura,ayah,text from arabic_text order by sura,ayah").fetchall()
    ayah_ids = {(s, a): i for i, (s, a, _) in enumerate(ayahs, start=1)}

    compiled = [(nm, [re.compile(p) for p in nm["patterns"]], [re.compile(r) for r in nm["raw"]]) for nm in NAMES]

    occurrences, review = [], []
    fallback_ayahs = 0
    stats = collections.Counter()
    for s, a, text in ayahs:
        toks = text.split()
        mapping, exact = align(toks, glyphs[(s, a)])
        if not exact:
            fallback_ayahs += 1
        ntoks = [norm(t) for t in toks]
        has_ref = ayah_has_allah_reference(ntoks)
        for i, n in enumerate(ntoks):
            pos = mapping[i]
            if not n or pos is None:
                continue
            rawtok = strip_signs(toks[i])
            n2 = norm_dagger(toks[i])
            for nm, pats, raws in compiled:
                if not any(p.match(n) or p.match(n2) for p in pats):
                    continue
                if raws and not any(r.search(rawtok) for r in raws):
                    continue
                if in_set(nm["exclude"], s, a, pos):
                    continue
                forced = in_set(nm["also"], s, a, pos)
                mode = nm["mode"]
                if mode == "all":
                    ok = True
                elif mode == "definite":
                    ok = is_definite(n) or forced
                elif mode == "whitelist":
                    ok = in_set(nm["only"], s, a, pos)
                else:  # with_allah
                    ok = is_definite(n) or has_ref or forced
                if ok:
                    occurrences.append((s, a, pos, nm["id"], toks[i], ayah_ids[(s, a)]))
                    stats[nm["id"]] += 1
                    ctx = " ".join(toks[max(0, i - 4):i + 5])
                    review.append(f"{nm['id']}\t{s}:{a}\tpos={pos}\ttok={toks[i]}\t{'' if exact else 'FALLBACK '}{ctx}")
                break  # first matching name wins for a token

    # attributes: explicit ayah lists (see ATTRIBUTES)
    text_by_ayah = {(s, a): text for s, a, text in ayahs}
    attr_stats = collections.Counter()
    for at in ATTRIBUTES:
        for entry in at["occ"]:
            s, a, pats = entry[0], entry[1], entry[2]
            allowed = set(entry[3]) if len(entry) > 3 else None
            toks = text_by_ayah[(s, a)].split()
            mapping, exact = align(toks, glyphs[(s, a)])
            found = 0
            for i, t in enumerate(toks):
                n2 = norm_dagger(t)
                if not n2 or mapping[i] is None:
                    continue
                if allowed is not None and (i + 1) not in allowed:
                    continue
                if any(re.match(p, n2) for p in pats):
                    occurrences.append((s, a, mapping[i], at["id"], t, ayah_ids[(s, a)]))
                    review.append(f"{at['id']}\t{s}:{a}\tpos={mapping[i]}\ttok={t}\t{'' if exact else 'FALLBACK '}"
                                  + " ".join(toks[max(0, i - 4):i + 5]))
                    found += 1
            if found == 0:
                print(f"WARNING attribute {at['id']} matched nothing in {s}:{a} ({pats})")
            attr_stats[at["id"]] += found

    if os.path.exists(OUT):
        os.remove(OUT)
    out = sqlite3.connect(OUT)
    out.executescript("""
    CREATE TABLE names(
      id TEXT PRIMARY KEY, sort_order INTEGER NOT NULL, arabic TEXT NOT NULL, transliteration TEXT NOT NULL,
      meaning TEXT NOT NULL, evidence TEXT NOT NULL, evidence_ref TEXT NOT NULL, note TEXT NOT NULL,
      sources TEXT NOT NULL, in_quran INTEGER NOT NULL, kind TEXT NOT NULL DEFAULT 'name'
    );
    CREATE TABLE occurrences(
      ayah_id INTEGER NOT NULL, sura INTEGER NOT NULL, ayah INTEGER NOT NULL, position INTEGER NOT NULL,
      name_id TEXT NOT NULL, form TEXT NOT NULL,
      PRIMARY KEY(sura, ayah, position)
    );
    CREATE INDEX occurrences_ayah_id ON occurrences(ayah_id);
    CREATE INDEX occurrences_name ON occurrences(name_id);
    CREATE TABLE meta(key TEXT PRIMARY KEY, value TEXT NOT NULL);
    """)
    for nm in NAMES:
        out.execute("insert into names values(?,?,?,?,?,?,?,?,?,1,'name')",
                    (nm["id"], nm["order"], nm["arabic"], nm["translit"], nm["meaning"], nm["evidence"],
                     nm["evidence_ref"], nm["note"], SRC))
    for k, (id, ar, tr, meaning, ref) in enumerate(SUNNAH):
        out.execute("insert into names values(?,?,?,?,?,?,?,?,?,0,'name')",
                    (id, 1000 + k, ar, tr, meaning, "", ref, "اسم ثابت في السنة النبوية ولم يرد لفظه في القرآن.", SRC))
    for at in ATTRIBUTES:
        out.execute("insert into names values(?,?,?,?,?,?,?,?,?,1,'attribute')",
                    (at["id"], 2000 + at["order"], at["arabic"], at["translit"], at["meaning"], at["evidence"],
                     at["evidence_ref"], at["note"], ATTR_SRC))
    out.executemany("insert or ignore into occurrences(sura,ayah,position,name_id,form,ayah_id) values(?,?,?,?,?,?)",
                    occurrences)
    out.execute("insert into meta values('version','2')")
    out.execute("insert into meta values('mushaf','madani')")
    out.execute("insert into meta values('note','تم توليد المواضع آليًا من نص المصحف مع قواعد استثناء مراجَعة؛ الشروح ملخصات على منهج أهل السنة والجماعة من المراجع المذكورة.')")
    out.commit()
    out.execute("VACUUM")
    out.close()

    with open(REVIEW, "w", encoding="utf-8") as f:
        f.write("\n".join(review))
    print("names:", len(NAMES) + len(SUNNAH), "attributes:", len(ATTRIBUTES), "occurrences:", len(occurrences), "fallback ayahs:", fallback_ayahs)
    for k, v in sorted(attr_stats.items(), key=lambda x: -x[1]):
        print(f"  attr {k:12s} {v}")
    for k, v in sorted(stats.items(), key=lambda x: -x[1]):
        print(f"  {k:12s} {v}")
    print("db size:", os.path.getsize(OUT))

if __name__ == "__main__":
    main()
