HIZB = "۞"
SAJDA = "۩"
MARKS = "ۖۗۘۙۚۛۜ۝ۣ۪ۭ۟۠ۡۢۤۧۨ۫۬"
SUKUN = "ۡ"

# ----------------------------------------------------------------------------- text helpers

def strip_signs(tok: str) -> str:
    return re.sub("[" + HIZB + SAJDA + MARKS + "]", "", tok)

def norm(tok: str) -> str:
    """Strip diacritics/marks, unify alef forms. Keeps hamza-on-line (used by ءالله)."""
    t = "".join(ch for ch in tok if not unicodedata.category(ch).startswith("M"))
    t = t.replace("ـ", "")
    t = strip_signs(t)
    t = t.replace("ٱ", "ا").replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    return t

def norm_dagger(tok: str) -> str:
    """Like [norm] but the uthmani superscript alef (U+0670) becomes a full alef, so that
    spellings such as ٱلۡخَٰلِقُ / وَٰسِعٌ / ٱلسَّلَٰمُ normalize to الخالق / واسع / السلام."""
    return norm(tok.replace("ٰ", "ا"))

def is_word_token(tok: str) -> bool:
    return bool(norm(tok).strip())

# ----------------------------------------------------------------------------- glyph alignment

def load_glyphs():
    g = sqlite3.connect(os.path.join(DB, "ayahinfo_1260.db"))
    rows = collections.defaultdict(list)
    for s, a, p, x1, x2, y1, y2 in g.execute(
        "select sura_number,ayah_number,position,min_x,max_x,min_y,max_y from glyphs "
        "order by sura_number,ayah_number,position"):
        rows[(s, a)].append((p, x2 - x1, y2 - y1))
    return rows

def is_mark(w, h):
    return w < 20 or h < 40

def align(tokens, glyphs):
    """Returns (token index -> glyph position or None, exact: bool)."""
    body = glyphs[:-1]  # last glyph is the ayah-number marker
    word_glyphs = [p for p, w, h in body if not is_mark(w, h)]
    widths = {p: w for p, w, h in body}
    if tokens and tokens[0].startswith(HIZB):
        word_glyphs = word_glyphs[1:]  # hizb symbol is a word-sized glyph
    word_idx = [i for i, t in enumerate(tokens) if is_word_token(t)]

    saj = [i for i, t in enumerate(tokens) if SAJDA in t]  # sajdah symbol follows its word
    if saj and len(word_glyphs) == len(word_idx) + len(saj):
        for i in saj:
            k = word_idx.index(i)
            del word_glyphs[k + 1]

    mapping = [None] * len(tokens)
    if len(word_glyphs) == len(word_idx):
        for k, i in enumerate(word_idx):
            mapping[i] = word_glyphs[k]
        return mapping, True

    # fallback: DP alignment using letter counts vs glyph widths
    PX = 22.0
    n, m = len(word_idx), len(word_glyphs)
    INF = 10 ** 9
    cost = [[INF] * (m + 1) for _ in range(n + 1)]
    back = [[None] * (m + 1) for _ in range(n + 1)]
    cost[0][0] = 0
    for i in range(n + 1):
        for j in range(m + 1):
            c = cost[i][j]
            if c >= INF:
                continue
            if i < n and j < m:
                L = len(norm(tokens[word_idx[i]]))
                mc = abs(widths[word_glyphs[j]] - PX * L)
                if c + mc < cost[i + 1][j + 1]:
                    cost[i + 1][j + 1] = c + mc
                    back[i + 1][j + 1] = ("m", i, j)
            if i < n and c + 60 < cost[i + 1][j]:
                cost[i + 1][j] = c + 60
                back[i + 1][j] = ("t", i, j)
            if j < m and c + 60 < cost[i][j + 1]:
                cost[i][j + 1] = c + 60
                back[i][j + 1] = ("g", i, j)
    i, j = n, m
    while i > 0 or j > 0:
        kind, pi, pj = back[i][j]
        if kind == "m":
            mapping[word_idx[pi]] = word_glyphs[pj]
        i, j = pi, pj
    return mapping, False

# ----------------------------------------------------------------------------- name rules
#
# mode:
#   "all"        every token matching the pattern counts (exclusions still apply)
#   "definite"   only tokens with the definite article count (plus `also`)
#   "whitelist"  only tokens inside `only` count
#   "with_allah" tokens count when definite, or when the ayah mentions Allah / Rabb+pronoun, or in `also`
# exclude / only / also: sets of (sura, ayah) or (sura, ayah, glyph_position)
# raw: extra regexes checked against the vowelled token (for cases like المَلِك vs المُلْك)

def P(base, prefixes="(و|ف)?(ب|ك)?", article="(ال|لل)", suffix=""):
    return "^" + prefixes + article + base + suffix + "$"

